// scripts/gen_scenes.mjs —— 场景入口真值生成器（S16）
//
// 输入：docs/scenes.json（场景 → 包列表，写死归属，人工维护）
// 输出：
//   image.<scene>/moon.pkg               （import 列表 + 别名）
//   image.<scene>/<scene>_scene.mbt      （pub using @alias {…} 再导出）
// 依据：各包 pkg.generated.mbti（`moon info` 产物，机器真值），不靠手抄 API。
//
// 用法：
//   node scripts/gen_scenes.mjs            # 写文件
//   node scripts/gen_scenes.mjs --check    # 只比对，漂移则 exit 1（CI 用）
//
// 冲突策略：同一场景内两个包导出同名符号时，按 scenes.json 中的包顺序**先到先得**，
// 后来者该项被跳过并写入生成文件顶部的「冲突清单」，不静默丢失。

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = process.env.ROOT ? path.resolve(process.env.ROOT) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = path.join(ROOT, 'docs', 'scenes.json');
const CHECK = process.argv.includes('--check');

const spec = JSON.parse(fs.readFileSync(SPEC, 'utf8'));

/** 解析一个包的 mbti，取出可再导出的值名与类型名。 */
function surface(pkgRel) {
  const file = path.join(ROOT, pkgRel, 'pkg.generated.mbti');
  if (!fs.existsSync(file)) {
    throw new Error(`缺少 ${pkgRel}/pkg.generated.mbti（先跑 moon info）`);
  }
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  const values = [];
  const types = [];
  let deprecated = 0;
  let pendingDeprecated = false;
  for (const line of lines) {
    // 属性行：`#deprecated` 紧跟一个声明，被标记者不再导出（否则 --deny-warn 直接失败）
    if (line.startsWith('#')) {
      pendingDeprecated = pendingDeprecated || line.startsWith('#deprecated');
      continue;
    }
    const v = line.match(/^pub fn (\w+)\(/);
    if (v) {
      if (pendingDeprecated) { deprecated += 1; pendingDeprecated = false; continue; }
      values.push(v[1]);
      continue;
    }
    const t = line.match(/^pub(?:\(all\))? (?:type|struct|enum) (\w+)/);
    if (t) {
      if (pendingDeprecated) { deprecated += 1; pendingDeprecated = false; continue; }
      types.push(t[1]);
    }
  }
  return { values, types, deprecated };
}

/** 包路径最后一个段作为别名，场景内重复则加序号。 */
function aliasOf(pkg, taken) {
  const seg = pkg.split('/').pop();
  let alias = seg;
  let n = 2;
  while (taken.has(alias)) {
    alias = `${seg}_${n}`;
    n += 1;
  }
  taken.add(alias);
  return alias;
}

function genScene(scene) {
  const takenAliases = new Set();
  const takenNames = new Set();
  const owner = new Map();
  const blocks = [];
  const conflicts = [];
  let deprecatedCount = 0;
  const imports = [];
  for (const pkg of scene.packages) {
    const alias = aliasOf(pkg, takenAliases);
    imports.push({ pkg, alias });
    const { values, types, deprecated } = surface(pkg);
    const items = [];
    // 同一包内 `pub fn Foo(...)` 是 `struct/enum Foo` 的构造器，与类型同名属正常，不记冲突。
    for (const name of types) {
      if (owner.has(name)) {
        if (owner.get(name) !== pkg) {
          conflicts.push(`${name}（${pkg} 的 type，已被 ${owner.get(name)} 占用）`);
        }
        continue;
      }
      owner.set(name, pkg);
      takenNames.add(name);
      items.push(`type ${name}`);
    }
    for (const name of values) {
      if (owner.has(name)) {
        if (owner.get(name) !== pkg) {
          conflicts.push(`${name}（${pkg} 的 fn，已被 ${owner.get(name)} 占用）`);
        }
        continue;
      }
      owner.set(name, pkg);
      takenNames.add(name);
      items.push(name);
    }
    deprecatedCount += deprecated;
    if (items.length === 0) {
      continue;
    }
    // 类型别名必须一条一语句：`type A, type B` 会被解析器判成 `unexpected token ,`（实测 [3002]）。
    for (const it of items) {
      if (it.startsWith('type ')) {
        blocks.push(`///|`+"\n"+`pub using @${alias} {${it}}`);
      }
    }
    const valueItems = items.filter((i) => !i.startsWith('type '));
    if (valueItems.length > 0) {
      const head = `///|`+"\n"+`pub using @${alias} {`;
      if (valueItems.length <= 3) {
        blocks.push(`${head}${valueItems.join(', ')}}`);
      } else {
        blocks.push(`${head}\n${valueItems.map((i) => `  ${i},`).join('\n')}\n}`);
      }
    }
  }
  const docTail = conflicts.length === 0
    ? '// 冲突清单：无（场景内符号名互不重叠）'
    : '// 冲突清单（先到先得，以下未再导出，仍可在原子包直接使用）：\n' +
      conflicts.map((c) => `//   - ${c}`).join('\n');
  const mbt = `// Generated by scripts/gen_scenes.mjs from docs/scenes.json + pkg.generated.mbti.
// DON'T EDIT IT —— 改归属请改 docs/scenes.json，然后 node scripts/gen_scenes.mjs。
// ${scene.title}：${scene.packages.length} 个原子包合成为一个入口，
// 下游 \`moon add walkzzz/${scene.module}\` 后不必再记子包路径。
// 本包零实现：全部是同签名再导出（\`pub using\`），实现与测试仍在原子包内。

${blocks.join('\n\n')}

${docTail}
`;
  const pkgFile = `import {\n${imports.map((i) => `  "walkzzz/${i.pkg}",`).join('\n')}\n}\n`;
  return { mbt, pkgFile, imports, conflicts, symbolCount: takenNames.size, deprecated: deprecatedCount };
}

const report = [];
let drift = false;
for (const scene of spec.scenes) {
  const dir = path.join(ROOT, scene.module);
  const { mbt, pkgFile, symbolCount, conflicts, deprecated } = genScene(scene);
  const files = [
    { rel: path.join(scene.module, 'moon.pkg'), content: pkgFile },
    { rel: path.join(scene.module, `${scene.module.split('.').pop()}_scene.mbt`), content: mbt },
  ];
  for (const f of files) {
    const abs = path.join(ROOT, f.rel);
    const old = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (CHECK) {
      if (old !== f.content) {
        console.error(`场景入口漂移: ${f.rel} 与 docs/scenes.json + mbti 生成结果不一致`);
        drift = true;
      }
    } else if (old !== f.content) {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, f.content);
    }
  }
  report.push({
    module: scene.module,
    packages: scene.packages.length,
    symbols: symbolCount,
    conflicts: conflicts.length,
    deprecated,
  });
}

if (CHECK) {
  console.log(JSON.stringify({ ok: !drift, scenes: report }, null, 2));
  process.exit(drift ? 1 : 0);
}
console.log(JSON.stringify({ ok: true, scenes: report }, null, 2));
