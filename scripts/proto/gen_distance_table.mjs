// 从 RFC 9649 §3.6.2.2.1 原文生成 MoonBit 距离映射表，避免手抄 120 项出错。
import fs from "node:fs";

const raw = `(0, 1), (1, 0), (1, 1), (-1, 1), (0, 2), (2, 0), (1, 2),
(-1, 2), (2, 1), (-2, 1), (2, 2), (-2, 2), (0, 3), (3, 0),
(1, 3), (-1, 3), (3, 1), (-3, 1), (2, 3), (-2, 3), (3, 2),
(-3, 2), (0, 4), (4, 0), (1, 4), (-1, 4), (4, 1), (-4, 1),
(3, 3), (-3, 3), (2, 4), (-2, 4), (4, 2), (-4, 2), (0, 5),
(3, 4), (-3, 4), (4, 3), (-4, 3), (5, 0), (1, 5), (-1, 5),
(5, 1), (-5, 1), (2, 5), (-2, 5), (5, 2), (-5, 2), (4, 4),
(-4, 4), (3, 5), (-3, 5), (5, 3), (-5, 3), (0, 6), (6, 0),
(1, 6), (-1, 6), (6, 1), (-6, 1), (2, 6), (-2, 6), (6, 2),
(-6, 2), (4, 5), (-4, 5), (5, 4), (-5, 4), (3, 6), (-3, 6),
(6, 3), (-6, 3), (0, 7), (7, 0), (1, 7), (-1, 7), (5, 5),
(-5, 5), (7, 1), (-7, 1), (4, 6), (-4, 6), (6, 4), (-6, 4),
(2, 7), (-2, 7), (7, 2), (-7, 2), (3, 7), (-3, 7), (7, 3),
(-7, 3), (5, 6), (-5, 6), (6, 5), (-6, 5), (8, 0), (4, 7),
(-4, 7), (7, 4), (-7, 4), (8, 1), (8, 2), (6, 6), (-6, 6),
(8, 3), (5, 7), (-5, 7), (7, 5), (-7, 5), (8, 4), (6, 7),
(-6, 7), (7, 6), (-7, 6), (8, 5), (7, 7), (-7, 7), (8, 6),
(8, 7)`;

const pairs = [...raw.matchAll(/\((-?\d+),\s*(-?\d+)\)/g)].map((m) => [Number(m[1]), Number(m[2])]);
if (pairs.length !== 120) {
  console.log(`WARN: 解析出 ${pairs.length} 项，应为 120`);
}

const dx = pairs.map((p) => p[0]);
const dy = pairs.map((p) => p[1]);

const fmt = (arr) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += 12) {
    lines.push("  " + arr.slice(i, i + 12).map((v) => `${v}`).join(", ") + ",");
  }
  return lines.join("\n");
};

const out = `///|
/// 距离映射表 X 偏移（RFC 9649 §3.6.2.2.1，120 项，由 scripts/proto/gen_distance_table.mjs 从 RFC 原文生成）
let vp8l_distance_dx : Array[Int32] = [
${fmt(dx)}
]

///|
/// 距离映射表 Y 偏移
let vp8l_distance_dy : Array[Int32] = [
${fmt(dy)}
]
`;
fs.writeFileSync("scripts/proto/distance_table.mbt.snippet", out, "utf8");
console.log(`生成 ${pairs.length} 项 → scripts/proto/distance_table.mbt.snippet`);
